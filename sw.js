async function cacheAllIndividually(cache, urls) { const failures=[]; await Promise.all(urls.map(async url=>{try{const request=new Request(url,{cache:'reload'});const response=await fetch(request);if(!response||!response.ok)throw new Error(`HTTP ${response?.status||'ERR'}`);await cache.put(url,response.clone())}catch(error){failures.push(url);console.warn('[RUPTURA offline] não foi possível pré-cachear',url,error)}}));return failures;}
self.addEventListener('install',event=>{event.waitUntil((async()=>{const cache=await caches.open(APP_CACHE);const failures=await cacheAllIndividually(cache,PRECACHE_URLS);for(const required of ['./index.html','./css/style.css','./js/core/level-loader.js','./js/main.js'])if(!(await cache.match(required)))throw new Error('Arquivo essencial sem cache: '+required);if(failures.length)console.warn('[RUPTURA offline] arquivos opcionais pendentes:',failures.length);await self.skipWaiting()})())});
self.addEventListener('activate',event=>{event.waitUntil((async()=>{const keys=await caches.keys();await Promise.all(keys.map(key=>(key!==APP_CACHE&&key!==RUNTIME_CACHE)?caches.delete(key):null));await self.clients.claim()})())});
self.addEventListener('fetch',event=>{const request=event.request;if(request.method!=='GET')return;const url=new URL(request.url);if(url.origin!==self.location.origin)return;const isDocument=request.mode==='navigate'||request.destination==='document';if(isDocument){event.respondWith(fetch(request).then(response=>{const copy=response.clone();caches.open(RUNTIME_CACHE).then(cache=>cache.put(request,copy));return response}).catch(()=>caches.match(request).then(r=>r||caches.match('./index.html'))));return}event.respondWith(caches.match(request).then(cached=>cached||fetch(request).then(response=>{if(!response||response.status!==200||response.type==='opaque')return response;const copy=response.clone();caches.open(RUNTIME_CACHE).then(cache=>cache.put(request,copy));return response}).catch(()=>caches.match('./index.html'))))});
